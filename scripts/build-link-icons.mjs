function dataUrl(name) {
  let svg = readFileSync(path.join(iconDir, `${name}.svg`), 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s+class="[^"]*"/g, '')
    .replace(/\s+role="img"/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  // A mask only uses alpha: give the stroked (Lucide) icons an opaque color and
  // a heavier stroke so they sit evenly next to the filled brand marks.
  svg = svg.replace('stroke="currentColor"', 'stroke="black"').replace('stroke-width="2"', 'stroke-width="2.5"');
  // Escape only what a data: URL in CSS needs; this keeps the snippet small.
  svg = svg.replace(/"/g, "'").replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');
  return `url("data:image/svg+xml,${svg}")`;
}

const base = `.markdown-rendered a.external-link`;
const lines = [];
lines.push(`/* link-icons:start (generated by scripts/build-link-icons.mjs) */`);
lines.push(`${base} {\n  --cosense-link-icon: ${dataUrl('lucide-arrow-up-right')};\n}`);
for (const [icon, sel] of rows) {
  const selectors = [
    ...(sel.href ?? []).map(s => `${base}${s}`),
    ...(sel.ext ?? []).map(s => `${base}${s}`),
    ...(sel.dataExt ?? []).map(s => `.markdown-rendered a.internal-link${s}`),
  ];
  const color = sel.color ? `\n  --cosense-link-icon-color: ${sel.color};` : '';
  lines.push(`${selectors.join(',\n')} {\n  --cosense-link-icon: ${dataUrl(icon)};${color}\n}`);
}
lines.push(`/* link-icons:end */`);

const css = readFileSync(cssPath, 'utf8');
const start = css.indexOf('/* link-icons:start');
const end = css.indexOf('/* link-icons:end */');
if (start < 0 || end < 0) throw new Error('link-icons markers not found');
const next = css.slice(0, start) + lines.join('\n\n') + css.slice(end + '/* link-icons:end */'.length);
writeFileSync(cssPath, next);
console.log(`Wrote ${rows.length + 1} icon rules; section is ${Buffer.byteLength(lines.join('\n\n'))} bytes`);
