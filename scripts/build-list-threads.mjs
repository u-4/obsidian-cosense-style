// Regenerates the list-thread section of cosense-scrapbox-style.css: a line
// from each list item on the path down to the current item, like Logseq's
// bullet threading. Covers list depths 1-6.
//   node scripts/build-list-threads.mjs
//
// Live Preview lines are flat siblings, so the path is found with :has():
// an ancestor at depth k is the nearest bulleted line of depth k before the
// active line, with no line of depth <= k in between. Reading view lists are
// nested, so the path is simply the hovered <li> and its ancestors.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const cssPath = path.join(root, 'cosense-scrapbox-style.css');
const MAX = 6;

// Desktop only: each cursor move re-evaluates the :has() rules for the
// rendered list lines (about 3-6 ms for 100-200 lines on a Mac), which phones
// and tablets can do without.
const lp = 'body:not(.is-mobile) .markdown-source-view.mod-cm6.is-live-preview';
const depth = k => `.HyperMD-list-line-${k}`;
const upTo = k => Array.from({ length: k }, (_, i) => depth(i + 1)).join(', ');
const bulleted = k => `${depth(k)}:not(.HyperMD-list-line-nobullet)`;
const bulletedUpTo = k => `:is(${upTo(k)}):not(.HyperMD-list-line-nobullet)`;
const activeDeeperThan = k => `.cm-active.HyperMD-list-line:not(${upTo(k)})`;
// The bulleted line of depth k on the path to the active line.
const ancestor = k => `${bulleted(k)}:has(~ ${activeDeeperThan(k)}):not(:has(~ ${bulletedUpTo(k)} ~ .cm-active))`;
const indent = k => `.cm-hmd-list-indent > .cm-indent:nth-child(${k})::after`;

const out = [];
out.push('/* list-threads:start (generated by scripts/build-list-threads.mjs) */');

// Live Preview: bullets on the path.
out.push([
  `${lp} .cm-active.HyperMD-list-line:not(.HyperMD-list-line-nobullet) .list-bullet::after`,
  ...Array.from({ length: MAX - 1 }, (_, i) => `${lp} ${ancestor(i + 1)} .list-bullet::after`),
].join(',\n') + ` {\n  background-color: var(--cosense-thread);\n  opacity: 1;\n}`);

// Live Preview: the straight part of the thread in column k, on lines between
// the depth-k ancestor and the next item on the path.
const straight = [];
for (let k = 1; k < MAX; k++) {
  const below = `.HyperMD-list-line:not(${upTo(k)})`;
  const noBreak = `:not(:has(~ ${bulletedUpTo(k)} ~ .cm-active))`;
  straight.push(`${lp} ${below}:has(~ ${bulleted(k + 1)} ~ ${activeDeeperThan(k)})${noBreak} ${indent(k)}`);
  straight.push(`${lp} ${below}:has(~ .cm-active${depth(k + 1)})${noBreak} ${indent(k)}`);
}
out.push(straight.join(',\n') + ` {\n  content: "";\n  top: 0;\n  bottom: 0;\n  border-inline-start: var(--cosense-thread-width) solid var(--cosense-thread);\n}`);

// Live Preview: the curve into each item's bullet, in the column of its parent.
const curves = [];
for (let j = 2; j <= MAX; j++) {
  curves.push(`${lp} .cm-active${bulleted(j)} ${indent(j - 1)}`);
  if (j < MAX) curves.push(`${lp} ${ancestor(j)} ${indent(j - 1)}`);
}
out.push(curves.join(',\n') + ` {\n  content: "";\n  top: 0;\n  height: var(--cosense-thread-lp-drop);\n  width: var(--cosense-thread-reach);\n  border-inline-start: var(--cosense-thread-width) solid var(--cosense-thread);\n  border-bottom: var(--cosense-thread-width) solid var(--cosense-thread);\n  border-end-start-radius: var(--cosense-thread-radius);\n}`);

// Live Preview: on the line right after an ancestor, the piece in that
// ancestor's column reaches up to just below its bullet.
const rises = [], riseCurves = [];
for (let k = 1; k < MAX; k++) {
  rises.push(`${lp} ${ancestor(k)} + .cm-line ${indent(k)}`);
  riseCurves.push(`${lp} ${ancestor(k)} + :is(.cm-active${bulleted(k + 1)}${k + 1 < MAX ? `, ${ancestor(k + 1)}` : ''}) ${indent(k)}`);
}
out.push(rises.join(',\n') + ` {\n  top: calc(-1 * var(--cosense-thread-lp-rise));\n}`);
out.push(riseCurves.join(',\n') + ` {\n  height: calc(var(--cosense-thread-lp-drop) + var(--cosense-thread-lp-rise));\n}`);

// Live Preview: place column k's line under the parent's bullet.
const columns = [];
for (let k = 1; k < MAX; k++) {
  columns.push(`${lp} ${indent(k)} {\n  inset-inline-start: calc(${k - 1} * var(--list-indent) + var(--cosense-thread-offset));\n}`);
}
out.push(columns.join('\n\n'));

out.push('/* list-threads:end */');

const css = readFileSync(cssPath, 'utf8');
const start = css.indexOf('/* list-threads:start');
const end = css.indexOf('/* list-threads:end */');
if (start < 0 || end < 0) throw new Error('list-threads markers not found');
writeFileSync(cssPath, css.slice(0, start) + out.join('\n\n') + css.slice(end + '/* list-threads:end */'.length));
console.log(`Wrote list threads for ${MAX} levels; section is ${Buffer.byteLength(out.join('\n\n'))} bytes`);
